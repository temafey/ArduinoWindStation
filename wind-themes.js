// ============================================================
// ТЕМЫ
// ============================================================
// Тема — это материал, из которого сделан интерфейс, а не набор цветов.
// Цвета здесь и так настраиваются (акцент, подложка, сцена), и ещё одна
// палитра ничего бы не добавила. Разница между темами — физика поверхности:
// как она отражает свет, есть ли у неё толщина и видно ли сквозь неё.
//
// Устроено на CSS-переменных панели (--pnl-*), а не на правках компонентов:
// панелей в дашборде под сотню, и тема, которую надо протаскивать пропсами,
// умерла бы на третьей.
//
// ---- Что взято из чужой работы и что из неё выброшено ----
//
// «Стеклянная» идёт за Liquid Glass из iOS 26. Apple описывает материал тремя
// слоями — блик, тень и подсветка, — и главный приём там не размытие, а
// линзирование: стекло не рассеивает свет, а преломляет его к краям, как
// настоящая линза (developer.apple.com/videos/play/wwdc2025/219).
//
// Линзирование в вебе делают SVG-фильтром с картой смещения, который
// подставляют в backdrop-filter: url(#…). Здесь этого нет — сознательно:
//   * такой backdrop-filter понимает только Chromium. Safari и Firefox
//     показывают вместо стекла пустое место, а половина заходов на этот
//     дашборд — с айфона;
//   * карта смещения — это PNG рядом с бандлом. У станции нет интернета,
//     а во флеше свободно около шестидесяти килобайт;
//   * карту приходится пересчитывать при каждой смене размера блока — а тут
//     размеры блоков пользователь тянет мышью.
// Остаются два слоя, которые воспроизводятся честно: подсветка и блик по
// фаске (градиентная рамка в маске, ярче сверху-слева). Толщину даёт
// внутренняя тень снизу.
//
// ---- Почему размытие включается не всегда ----
//
// Первая версия ставила backdrop-filter: blur(20px) на каждую панель, на шапку
// и на панель вкладок. Мерялось это в настоящем Chrome (Intel UHD, окно во всю
// ширину 3440-го монитора, восемь панелей, варианты чередуются на одной и той
// же странице, медиана шести кругов, замер с прокруткой и с удвоенным
// растром). Честный итог замера: **разницы между вариантами поймать не
// удалось** — прогон к прогону разброс оказался больше, чем разница между
// «с размытием» и «без». Первые прогоны показывали 51 против 61 fps, но при
// повторе это не воспроизвелось, и верить им нельзя.
//
// Поэтому решение принято не по замеру, а по тому, что видно глазом:
// **размывать под стеклом чаще всего нечего**. Все встроенные сцены — гладкие
// градиенты, а гладкий градиент после размытия остаётся тем же градиентом.
// Расплата за эффект есть, самого эффекта нет. Размытие видно ровно в двух
// случаях: под стеклом своя картинка или подложка с мелкой фактурой (зерно,
// миллиметровка, развёртка, карбон). Только там оно и включается — решает
// `glassRich()`, а дашборд вешает на корень класс `gl-deep`.
//
// По той же причине размытия лишились шапка и панель вкладок: они ничем не
// перекрыты (страница под ними не проезжает — они не липкие), и под ними тот
// же ровный фон. Две полосы во всю ширину экрана размывались каждый кадр
// впустую. У модального окна за спиной, наоборот, живой дашборд — там
// размытие осталось, и оно там не украшение, а читаемость.
//
// Отсвет по стеклу оставлен, но замедлен вдвое и разведён по времени сильнее.
// Слой композитора ему намеренно не прибивается: вариант с will-change на всех
// восьми панелях мерялся отдельно и быстрее не стал — вечные слои на
// встроенной видеокарте стоят памяти и полосы, а слой на время самого движения
// Chromium заводит и без подсказки.
//
// Если у кого-то стекло всё-таки тормозит, у него есть прямой рычаг: тумблер
// «Размытие под стеклом» в кастомизации выключает backdrop-filter совсем.
//
// «Матовая» — противоположность. Матовая поверхность рассеивает свет во все
// стороны и потому не даёт бликов вовсе, а чёрный на ней выглядит глубже и
// ровнее, чем на глянце. Значит, из интерфейса убирается всё зеркальное:
// свечение текста, внешние тени, светлые кромки. Вместо них — микрорельеф
// настоящим шумом и одна мягкая тень внутрь, от которой панель читается как
// углубление, а не как наклейка.
//
// «Фосфор» — своя. Дашборд и так наполовину состоит из радарной развёртки,
// картушки и шкал; довести его до электронно-лучевой трубки было ближе всего.
// Тут собраны настоящие болезни трубки, а не просто зелёный цвет:
//   * прогрев — картинка разжимается из яркой строки, как при включении;
//   * строчная развёртка и кадровая полоса, ползущая по экрану;
//   * мерцание накала — редкие провалы яркости, а не ровный синус;
//   * срыв кадровой синхронизации — полоса гашения проезжает экран, и на её
//     кромке картинка рвётся;
//   * потеря строчной синхронизации — развёртка дёргается на строку-две;
//   * и главное: у трубки нет плавности. Луч рисует кадр за кадром, поэтому
//     тема подменяет обе кривые плавности на `steps()`, и ступенчатым
//     становится всё разом — появление панелей, тумблеры, вкладки, стрелки.
//     Интерфейс начинает ощущаться тормозящим, хотя не тормозит.
// Всё это живёт в плёнке поверх экрана и в переменных, а не в компонентах:
// содержимое дашборда о теме по-прежнему ничего не знает.

// Блик по фаске. Ярче всего сверху-слева — оттуда в интерфейсе всегда светит,
// — быстро гаснет и слегка возвращается снизу-справа отражением от подложки.
const RING =
  "linear-gradient(148deg, rgba(255,255,255,0.95), rgba(255,255,255,0.34) 18%," +
  " rgba(255,255,255,0.05) 42%, rgba(255,255,255,0.02) 62%, rgba(255,255,255,0.45))";

// Фактуры с мелким зерном или сеткой: под стеклом они видны, и размытие по
// ним работает. Гладкий градиент и глянец размывать бессмысленно.
const ROUGH = new Set(["grain", "brushed", "carbon", "grid", "scanlines"]);

// Есть ли под стеклом что размывать. Своя картинка — всегда да: у фотографии
// высокая частота, и размытие по ней и есть весь эффект.
export function glassRich(settings, hasBgImage) {
  if (settings.theme !== "glass") return false;
  if (settings.glassBlur === false) return false;
  if (settings.scene === "custom" && hasBgImage) return true;
  return ROUGH.has(settings.texture);
}

