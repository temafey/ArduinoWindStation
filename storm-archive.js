// Справочный архив разрушительных смерчей.
//
// Зачем он вообще нужен, если рядом есть живой слой предупреждений: рейтинг по
// шкале Фудзиты присваивается **после** наземного обследования разрушений, а не
// во время смерча. У активного смерча рейтинга не существует в принципе —
// служба погоды выпускает предупреждение с признаком «обнаружен радаром» или
// «подтверждён наблюдателем», и всё. Поэтому цветовая шкала EF может работать
// только по завершённым, обследованным событиям; живой слой раскрашивается по
// уровню угрозы, а не по EF.
//
// Числа — по официальным обследованиям NWS и записям NCEI Storm Events.
// События до 2007 года оценены по исходной шкале Фудзиты (F), после — по
// доработанной (EF); подменять одно другим нельзя, поэтому в поле `scale`
// хранится ровно то обозначение, под которым событие занесено в реестр.
// Где цифра спорна или в источниках расходится — стоит null, а не среднее
// арифметическое между версиями.

