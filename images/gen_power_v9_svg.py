# -*- coding: utf-8 -*-
"""КАК ПИТАЕТСЯ «+» ШИНА · схема v9 (выключатель KCD4 на два полюса).

Картинка для wiring-v9.html. Прямая наследница power_v8.svg: тот же приём — выкинуть
всё, что не переносит «+», и оставить путь целиком, от розетки до пина «5V».

Что здесь нарисовано и, главное, чего нет:

  * НЕТ БАНОК. Ни батарейного холдера, ни электролитов C1/C4: они не участвуют в
    переносе питания (C1 висит на узле ШИНА параллельно, холдер — просто источник),
    а места занимают половину картинки и сбивают счёт стадий.
  * НЕТ ЗЕМЛИ. Ни одного «−» провода: земля разобрана отдельно, и её линии здесь
    только мешали бы читать плюсовую цепь.
  * НЕТ МОДЕМА, светодиодов и делителей — только шесть стадий переноса «+».

Чем v9 отличается от v8 ровно на этой картинке:

  * выключатель стал ДВУХПОЛЮСНЫМ, и второй полюс (B) встал в разрыв самой шины,
    сразу за диодным ИЛИ. Поэтому стадия 4 из «одного длинного провода 39g → кол.16»
    превратилась в «39j → полюс B → нижний «+» рельс, кол.43»;
  * питание платы пошло СПРАВА НАЛЕВО: нижний «+» правый → связка кол.58 → верхний
    «+» правый → и только потом через мост 31↔32 налево, к ESP32;
  * единственной точкой отказа стала не перемычка, а МОСТ 31↔32 (стадия 6). Отойдёт
    он — датчик на 12 В останется жив, а ESP32 умрёт. Ровно поэтому он нарисован
    вдвое толще и с гало.

Цвета — те же десять плюсовых цепей, что и на большой схеме (P1…P10): один и тот же
провод на обеих картинках одного цвета, иначе их не сопоставить.

Вход:  bb_lib
Выход: images/power_v9.svg
"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import bb_lib as bb

NCOLS = 63
RAIL_INSET = 2
RAIL_TP, RAIL_TM = 250, 262           # верх: «+» LOAD / «−» GND (ряды отверстий)
RAIL_BP, RAIL_BM = 506, 518           # низ:  «+» LOAD / «−» GND
CUT = 606.5                           # разрез рельсов, между кол. 31 и 32
LOW_A, LOW_B = 490, 498               # те же коридоры, что в gen_wiring_v9_svg.py
SWX, SWY, SWW, SWH = 790, 620, 300, 190
W_CANVAS, VH = 1700, 880

# ═══════════════════════════════════════ 0. ДЕСЯТЬ ПЛЮСОВЫХ ЦЕПЕЙ
# Значения продублированы из gen_wiring_v9_svg.py намеренно: генераторы не импортируют
# друг друга (у каждого своя раскладка), а расхождение цвета между двумя картинками
# одного узла — худшее, что здесь может случиться. При правке менять В ОБОИХ местах.
P1  = "#ff7043"   # +5 В адаптера
P2  = "#7d1128"   # «+» пакета 18650 через F1
P4  = "#c25e00"   # OUT+ TP4056 ДО полюса A
P5  = "#a97400"   # колонка 51 — ПОСЛЕ полюса A
P6  = "#6b8e23"   # выход Boost#2, 5.14 В
P7  = "#00838f"   # узел ШИНА ДО полюса B
P8  = bb.PLUS     # «+» LOAD ПОСЛЕ полюса B — канонический красный
P9  = "#c2185b"   # 12 В на датчик

RED = bb.PLUS
DIM = "#9a948a"                       # то, что не несёт «+»
INK = "#1a1a1a"

X = bb.colx
Y = bb.ROWY

# ═══════════════════════════════════════ 1. МАКЕТКА И ОРИЕНТИРЫ
board, r3c, r4c = bb.breadboard(bottom="+-", ncols=NCOLS, rail_inset=RAIL_INSET)

# Штатные подписи колонок идут с 20-й: слева их не было, там всегда стояла плата.
# Здесь по колонкам считают путь, значит нужны и левые.
extra_cols = "".join(f'<text x="{X(c)}" y="286">{c}</text>' for c in (1, 3, 5, 10, 15, 16))

esp = bb.esp32_38(subtitle="38-pin · ESP-32U", antenna=False, highlight=["5V"])
flash = bb.flash_warn(label="")

tp4056 = bb.mod_inline(
    45, 50, "b", "f",
    [(45, "b", "IN−", bb.GNDc, -10), (50, "b", "IN+", P1, -10),
     (45, "f", "OUT−", bb.GNDc, 14), (46, "f", "B−", bb.PURPLE, 26),
     (49, "f", "OUT+", P4, 14), (50, "f", "B+", P2, 26)],
    "TP4056 · Type-C", "заряд + защита DW01",
    over_x=14, over_y=38, title_y=384, sub_y=395)

boost2 = bb.mod_inline(
    53, 57, "c", "h",
    [(55, "c", "IN+", P5, 11), (56, "c", "IN−", bb.GNDc, 24),
     (53, "h", "OUT−", bb.GNDc, -11), (57, "h", "OUT+", P6, -11)],
    "Boost#2", "5.14 В от батареи",
    over_x=4, over_y=17, title_y=384, sub_y=395)

boost1 = bb.mod_inline(
    59, 63, "c", "h",
    [(61, "c", "IN+", P8, 11), (62, "c", "IN−", bb.GNDc, 24),
     (59, "h", "OUT−", bb.GNDc, -11), (63, "h", "OUT+", P9, -11)],
    "Boost#1", "12 В для датчика",
    over_x=4, over_y=17, title_y=384, sub_y=395)

# Контакты стоят ровно под своими колонками: B2→43, B1→«46+3», A1→49, A2→51.
# Из-за этого корпус и растянут на 300 px — каждый провод падает вертикально.
sw1 = bb.switch_dpst(
    SWX, SWY, SWW, SWH,
    [(X(49), SWY, "A1"), (X(51), SWY, "A2"), (856, SWY, "B1"), (X(43), SWY, "B2")],
    (SWX + 170, SWY + 42, 118, 120),
    title="SW1 · KCD4 — ДВА полюса",
    subtitle="A: разрыв OUT+ TP4056 (до 1.83 А)   ·   B: разрыв шины после ИЛИ (~0.2 А)",
    title_x=SWX + 165, title_anchor="start")

parts = (bb.diode_schottky(37, 39, "h", "D1", cathode="right") +
         bb.diode_schottky(39, 41, "h", "D2", cathode="left") +
         bb.ptc(42, 44, "j", ""))

# ═══════════════════════════════════════ 2. «+» РЕЛЬСЫ — ЧТО ЖИВОЕ, А ЧТО НЕТ
# В v8 все четыре полурельса были одной цепью. В v9 связка кол.20 снята, поэтому
# НИЖНЯЯ ЛЕВАЯ половина «+» не соединена ни с чем и не используется вовсе.
# Показать это цветом важнее, чем подписать: пустой рельс на картинке выглядит
# точно так же, как рабочий.
def band(y, x0, x1, color=P8, op=0.16):
    return (f'<rect x="{x0:.0f}" y="{y-7}" width="{x1-x0:.0f}" height="14" rx="4" '
            f'fill="{color}" fill-opacity="{op}"/>')

L0, R1 = X(3) - 9, X(61) + 9
rail_tint = (
    band(RAIL_TP, L0, R1) +                       # верхний «+» смощён — одна цепь
    band(RAIL_BP, X(43) - 9, R1, op=0.14) +       # нижний «+» ПРАВЫЙ — живой
    band(RAIL_BP, L0, CUT, color=DIM, op=0.22) +  # нижний «+» ЛЕВЫЙ — мёртвый
    f'<text x="{R1:.0f}" y="222" font-size="10.5" font-weight="700" '
    f'fill="{P8}" text-anchor="end">'
    f'верхний «+» смощён через разрез — обе половины ОДНА цепь</text>'
    f'<text x="{L0+8:.0f}" y="{RAIL_BP-8:.0f}" font-size="9.5" font-weight="700" '
    f'fill="#7a7268">нижний «+» ЛЕВЫЙ в v9 не используется: связка кол.20 снята</text>')

cut_marks = (f'<line x1="{CUT}" y1="238" x2="{CUT}" y2="276" stroke="#c0392b" '
             f'stroke-width="1.6" stroke-dasharray="3 3"/>'
             f'<line x1="{CUT}" y1="494" x2="{CUT}" y2="530" stroke="#c0392b" '
             f'stroke-width="1.6" stroke-dasharray="3 3"/>'
             f'<text x="{CUT-6:.0f}" y="546" font-size="9" font-weight="700" '
             f'fill="#c0392b" text-anchor="end">разрез рельсов</text>')

# ═══════════════════════════════════════ 3. ПУТЬ ПИТАНИЯ
def path(pts, w=4.2, color=P8, dots="none", op=1.0, hops=None):
    d = bb.hop_dpath(pts, hops or [], r=8)
    s = (f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{w}" '
         f'stroke-linejoin="round" stroke-linecap="round" stroke-opacity="{op}"/>')
    r = max(3.2, w * 1.15)
    if dots in ("both", "start"):
        s += f'<circle cx="{pts[0][0]:.1f}" cy="{pts[0][1]:.1f}" r="{r:.1f}" fill="{color}"/>'
    if dots in ("both", "end"):
        s += f'<circle cx="{pts[-1][0]:.1f}" cy="{pts[-1][1]:.1f}" r="{r:.1f}" fill="{color}"/>'
    return s

def tag(x0, y0, w, h, title, sub, color=RED):
    return (f'<rect x="{x0}" y="{y0}" width="{w}" height="{h}" rx="8" fill="#fff5f3" '
            f'stroke="{color}" stroke-width="2"/>'
            f'<text x="{x0+w/2:.0f}" y="{y0+17}" font-size="11.5" font-weight="700" '
            f'fill="{color}" text-anchor="middle">{title}</text>'
            f'<text x="{x0+w/2:.0f}" y="{y0+31}" font-size="9" fill="#7a6f62" '
            f'text-anchor="middle">{sub}</text>')

GAP = (X(51) + X(52)) / 2.0

# ─ стадия 1 (P1): адаптер → анод D1 (кол.37) → [D1] → кол.39
s1 = (tag(20, 546, 118, 38, "АДАПТЕР 5 В", "панельный, 2 А", P1) +
      path([(138, 562), (X(37), 562), (X(37), Y["h"])], color=P1, dots="end"))

# ─ стадия 2 (P2 → P4 → P5): банка → F1 → B+ → TP4056 → OUT+ → ПОЛЮС A → Boost#2
s2 = (tag(20, 586, 118, 38, "«+» БАНКИ", "18650, через F1", P2) +
      path([(138, 602), (X(42), 602), (X(42), Y["j"])], color=P2, dots="end") +
      path([(X(44), Y["j"]), (X(44), LOW_A), (X(50), LOW_A), (X(50), Y["j"])],
           color=P2, dots="both") +
      # ⚠ полюс A стоит ровно там же, где в v8 стоял однополюсный SW1 — в разрыве OUT+.
      path([(X(49), Y["j"]), (X(49), SWY)], color=P4, dots="start") +
      path([(X(51), SWY), (X(51), Y["j"])], color=P5, dots="end") +
      path([(X(51), Y["i"]), (X(51), 470), (GAP, 470), (GAP, 290), (X(55), 290),
            (X(55), Y["c"])], color=P5, dots="both"))

# ─ стадия 3 (P6): выход Boost#2 → анод D2 (кол.41) → [D2] → кол.39
s3 = path([(X(57), Y["h"]), (X(57), LOW_B), (X(41), LOW_B), (X(41), Y["h"])],
          color=P6, dots="both")

# ─ стадия 4 (P7 → P8): узел ШИНА → ПОЛЮС B → нижний «+» рельс, кол.43.
# Здесь и живёт всё отличие v9: раньше отсюда уходил один длинный провод в кол.16
# мимо выключателя, и «выключено» при воткнутом адаптере не значило ничего.
s4 = (path([(X(39), Y["h"]), (X(39), Y["j"])], color=P7, w=5.0) +
      path([(X(39), Y["j"]), (X(39), 566), (856, 566), (856, SWY)], color=P7,
           w=5.0, dots="both", hops=[(X(43), 566, 9)]) +
      path([(X(43), SWY), (X(43), RAIL_BP)], color=P8, w=5.0, dots="both"))

# ─ стадия 5 (P8 → P9): нижний «+» правый → связка кол.58 → верхний «+» правый → Boost#1
LINK58 = X(58) - 1
s5 = (path([(X(43), RAIL_BP), (LINK58, RAIL_BP), (LINK58, RAIL_TP),
            (X(61), RAIL_TP), (X(61), Y["a"])], color=P8, dots="end") +
      path([(X(63), Y["h"]), (X(63), 600), (1150, 600)], color=P9, dots="start") +
      tag(1150, 582, 150, 38, "12 В НА ДАТЧИК", "по кабелю на мачту", P9))

# ─ стадия 6 (P8): мост «+» 31↔32 → верхний «+» ЛЕВЫЙ → кол.3 → диагональ → 1a → «5V».
