// На каком масштабе появляется каждый ранг. Пороги подобраны так, чтобы подписи
// никогда не наезжали друг на друга: на мировом виде их меньше трёх десятков.
export function visibleCities(z) {
  const maxRank = z >= 5 ? 3 : z >= 1.9 ? 2 : 1;
  return CITIES.filter((c) => c.rank <= maxRank);
}
