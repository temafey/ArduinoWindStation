// Один осциллятор на писк, контекст создаётся лениво. Браузеры не дают
// запустить звук до первого касания страницы — поэтому первые сообщения
// в любом случае тихие, и никакого «внезапно заорало при открытии» не будет.
function useBeeper(enabled) {
  const ctxRef = useRef(null);

  const tone = useCallback((freq, dur = 0.03, gain = 0.03, type = "square") => {
    if (!enabled) return;
    try {
      const AC = window.AudioContext || window.webkitAudioContext;
      if (!AC) return;
      if (!ctxRef.current) ctxRef.current = new AC();
      const ctx = ctxRef.current;
      if (ctx.state === "suspended") ctx.resume();
      const osc = ctx.createOscillator();
      const amp = ctx.createGain();
      osc.type = type;
      osc.frequency.value = freq;
      // Короткий спад вместо резкого обрыва: щелчок на срезе слышно сильнее,
      // чем сам тон.
      amp.gain.setValueAtTime(gain, ctx.currentTime);
      amp.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime + dur);
      osc.connect(amp);
      amp.connect(ctx.destination);
      osc.start();
      osc.stop(ctx.currentTime + dur);
    } catch { /* звук — не то, из-за чего можно ломать страницу */ }
  }, [enabled]);

  return useMemo(() => ({
    type: () => tone(540 + Math.floor(Math.random() * 5) * 40, 0.022, 0.022),
    done: () => { tone(660, 0.05, 0.03); setTimeout(() => tone(880, 0.06, 0.026), 55); },
    next: () => tone(440, 0.04, 0.026),
    finish: () => [0, 90, 180].forEach((d, i) => setTimeout(() => tone([660, 880, 1175][i], 0.08, 0.03), d)),
  }), [tone]);
}

