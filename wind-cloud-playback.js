// ============================================================
// БУФЕР ВОСПРОИЗВЕДЕНИЯ ОБЛАЧНЫХ КАДРОВ
// ============================================================
// Здесь нет ни сети, ни React — только логика «что показать в этот момент».
// Вынесено отдельно именно ради этого: такую логику можно прогнать синтетикой
// и проверить руками, а внутри компонента её пришлось бы ловить глазами на
// живой станции.
//
// ---- Почему шаг ровно 50 мс, а не «интервал прихода / число отсчётов» ----
//
// Станция снимает датчик каждые CLOUD_SAMPLE_MS = 50 мс и держит СКОЛЬЗЯЩИЙ
// буфер на четыре отсчёта (memmove), а после публикации обнуляет счётчик.
// Значит в батарейном режиме (пакет раз в секунду) пакет несёт ПОСЛЕДНИЕ
// 200 мс секунды, а остальные шестнадцать отсчётов станция выбросила сама.
//
// Отсюда единственно верный шаг воспроизведения — 50 мс. Растянуть пачку на
// измеренный интервал прихода (250 мс на отсчёт при 1 Гц) было бы куда
// «ровнее» на вид, но это растянуло бы двухсотмиллисекундный порыв
// турбулентности в секундный, то есть исказило бы физику ради красивой
// картинки. Пауза 800 мс из каждой секунды — настоящая: станция в это время
// действительно ничего не рассказала.

// Шаг выдачи. Константа прошивки, а не производная от чего-либо здесь.
export const STEP_MS = 50

// Границы бюджета задержки. Нижняя — чтобы буфер не схлопывался в ноль на
// ровной доставке, верхняя — чтобы зритель не смотрел трёхсекундной давности
// ветер, думая, что смотрит живой.
const BUDGET_MIN = 400
const BUDGET_MAX = 3000

// Сколько времён прихода помним. Восьми хватает, чтобы в окне при 5 Гц
// оказалась хотя бы одна настоящая пауза между пачками.
const RING = 8

// Пока наблюдений меньше полутора секунд, о периоде доставки не известно
// НИЧЕГО. Считать его по расстоянию между пакетами внутри одной пачки нельзя:
// они приходят почти одновременно, период получился бы нулевым, и первая же
// пачка из пяти пакетов (esp-mqtt разгребает outbox пробуждениями, примерно
// раз в секунду) была бы наполовину выброшена как «переполнение».
const RING_WARMUP_MS = 1500

// Разрыв больше трёх пакетов — это уже не потеря, а дыра: доигрывать её
// нечем, и склеивать края тоже нечем.
const GAP_RESET = 3

function clamp (v, lo, hi) {
  return v < lo ? lo : v > hi ? hi : v
}

// Создаёт буфер. Все внешние зависимости — параметрами, чтобы прогонять
// синтетикой в node, где нет ни performance, ни requestAnimationFrame.
//
// emit(frame)  — куда отдавать готовый кадр
// motionOff    — режим «анимация выключена» (см. ниже)
// now/raf/caf  — часы и планировщик кадров
export function createPlayback (opts) {
  const emit = opts.emit
  const motionOff = Boolean(opts.motionOff)
  const now = opts.now || (() => performance.now())
  const raf = opts.raf || ((fn) => requestAnimationFrame(fn))
  const caf = opts.caf || ((id) => cancelAnimationFrame(id))

  const st = {
    buf: [],            // FIFO из {v, g} — по одному отсчёту на 50 мс
    ring: [],           // времена прихода последних пакетов
    lastQ: null,        // счётчик пакетов станции
    sessionId: null,    // нонс загрузки станции, приходит в state
    nextDueAt: null,    // когда пора отдать следующий отсчёт (null = ещё не заведён)
    lastState: null,    // последний разобранный state — основа кадра
    lost: 0,            // сколько пакетов не доехало
    dropped: 0,         // сколько отсчётов выброшено переполнением
    online: null,       // null = ещё не знаем
  }

  let frame = null

  function clear () {
    st.buf.length = 0
    st.nextDueAt = null
  }

  function stopLoop () {
    if (frame !== null) {
      caf(frame)
      frame = null
    }
  }

  // ⛔ Цикл выдачи живёт на requestAnimationFrame, а не на setInterval, и это
  // не вкусовщина. rAF замирает в фоновой вкладке — ровно то, что нужно:
  // буфер там переполнится и ВЫБРОСИТ лишнее, а вернувшийся зритель увидит
  // настоящее «сейчас». setInterval в фоне зажимается до секунды и более, а
  // по возвращении отдаёт накопленное пачкой, то есть делает именно то
  // догоняние, которого здесь быть не должно: минута протухшего ветра,
  // проигранная на ускоренной перемотке, — это неправда в чистом виде.
  // Тот же rAF уже служит часами всему дашборду (useSmooth).
  function step () {
    frame = raf(step)
    const t = now()
    if (!st.buf.length) return
    if (st.nextDueAt === null || t >= st.nextDueAt) {
      const s = st.buf.shift()
      push(s)
      // max(now, …) гасит догоняние: после длинной паузы (свёрнутая вкладка,
      // залипший кадр) расписание не тянется из прошлого, а начинается заново
      // от текущего момента.
      st.nextDueAt = Math.max(t, (st.nextDueAt === null ? t : st.nextDueAt) + STEP_MS)
    }
  }

  function startLoop () {
    if (motionOff || frame !== null) return
    frame = raf(step)
  }

  function push (s) {
    emit(st.lastState ? { ...st.lastState, speed: s.v, gust: s.g } : { speed: s.v, gust: s.g })
  }

  // Бюджет задержки: сколько миллисекунд молчания буфер обязан уметь
  // пережить. Считается по САМОЙ ДЛИННОЙ паузе между приходами, а не по
  // средней: пачка из пяти пакетов разом — это нормальный режим доставки
  // (очередь esp-mqtt), и потолок обязан вмещать её целиком.
  function budget () {
    const r = st.ring
    if (r.length < 2 || r[r.length - 1] - r[0] < RING_WARMUP_MS) return BUDGET_MAX
    let gap = 0
    for (let i = 1; i < r.length; i++) gap = Math.max(gap, r[i] - r[i - 1])
    return clamp(1.3 * gap, BUDGET_MIN, BUDGET_MAX)
  }

  // Переполнение считается по бюджету задержки, а не по числу отсчётов.
  // Фиксированный потолок выбрасывал бы восемь настоящих измерений в секунду
  // всякий раз, когда приходит пачка, — то есть в штатном режиме.
  function trim () {
    const maxBuf = Math.ceil(budget() / STEP_MS)
    if (st.buf.length <= maxBuf) return
    const keep = Math.floor(maxBuf * 0.75)
    st.dropped += st.buf.length - keep
    // Выбрасываем С ГОЛОВЫ: старое уже неправда, а новое — это «сейчас».
    st.buf.splice(0, st.buf.length - keep)
  }

  // Полный сброс. Нужен, когда станция перезагрузилась: её счётчик пакетов
  // начинается заново, и сравнивать его со старым бессмысленно.
  function reset () {
    clear()
    st.ring.length = 0
    st.lastQ = null
  }

  return {
    // Живой пакет станции: {"q":<счётчик>,"s":[до 4 скоростей],"g":<порыв>}
    live (pkt) {
      if (!pkt || typeof pkt !== 'object') return
      const t = now()
      st.ring.push(t)
      if (st.ring.length > RING) st.ring.shift()

      const q = Number(pkt.q)
      if (Number.isFinite(q)) {
        if (st.lastQ !== null) {
          const d = q - st.lastQ
          if (d < 0) {
            // ⚠️ Счётчик пошёл назад — это перезагрузка станции, а не потеря
            // сорока тысяч пакетов. Настоящее подтверждение придёт со сменой
            // sessionId в топике state; здесь достаточно не приписать станции
            // чудовищную потерю и начать считать заново.
            reset()
          } else if (d > 1) {
            st.lost += d - 1
            // Ничего не достраиваем: выдуманный отсчёт ветра — это выдуманное
            // измерение, а показывать выдуманное метеостанция не должна.
            if (d - 1 > GAP_RESET) clear()
          }
        }
        st.lastQ = q
      }

      const g = Number(pkt.g)
      const gust = Number.isFinite(g) ? g : 0
      // Длина s переменная, до четырёх: станция шлёт столько, сколько успела
      // снять с прошлой публикации. Полагаться на четвёрку нельзя.
      const s = Array.isArray(pkt.s) ? pkt.s : []
      if (!s.length) return

      if (motionOff) {
        // Режим «анимация выключена». Буфер и rAF не заводятся вовсе: при
        // выключенном сглаживании стрелка проваливается на сырое значение, и
        // двадцать прыжков в секунду читаются ровно так же, как один, только
        // жгут батарею телефона.
        //
        // Отдаём ПОСЛЕДНИЙ отсчёт пачки, а не средний: это «значение сейчас»,
        // а пик по этой пачке зритель и так видит в поле порыва.
        const v = Number(s[s.length - 1])
        if (Number.isFinite(v)) push({ v, g: gust })
        return
      }

      for (const raw of s) {
        const v = Number(raw)
        if (Number.isFinite(v)) st.buf.push({ v, g: gust })
      }
      trim()
      // Расписание никогда не отстаёт от настоящего момента. Без этой строки
      // после паузы (буфер опустел, следующая пачка пришла через секунду)
      // срок «пора выдавать» оставался в прошлом, и первые два отсчёта новой
      // пачки выскакивали подряд, через один кадр вместо 50 мс. Мелочь на
      // вид — но это ровно то догоняние, которого здесь быть не должно.
      if (st.nextDueAt === null || st.nextDueAt < t) st.nextDueAt = t
      startLoop()
    },

    // Медленная половина — ровно объект /api/data плюс sessionId. Он же
    // основа каждого живого кадра: живой пакет несёт только скорость и порыв.
    state (json) {
      if (!json || typeof json !== 'object') return
      const sid = json.sessionId
      if (sid && st.sessionId && sid !== st.sessionId) {
        // Станция перезагрузилась. Всё накопленное относится к прошлой жизни
        // платы: счётчик пакетов там начинался с нуля, и склеивать два ряда
        // в один нельзя.
        reset()
        st.lost = 0
        st.dropped = 0
      }
      if (sid) st.sessionId = sid
      st.lastState = json
    },

    // {"online":true|false} — второе приходит LWT'ом, когда станция умерла
    // не попрощавшись.
    status (obj) {
      const online = obj && obj.online === true
      st.online = online
      if (!online) {
        // Выдачу останавливаем и буфер чистим: доигрывать хвост мёртвой
        // станции незачем. А вот последний retained state продолжаем
        // показывать — это последнее, что о ней достоверно известно.
        stopLoop()
        clear()
      }
    },

    // Связь пропала на нашей стороне. Ровно то же, что и офлайн станции, но
    // без пометки «станция мертва»: мёртв может быть канал.
    hold () {
      stopLoop()
      clear()
      // Счётчик пакетов тоже забываем. За время обрыва станция отсчитала
      // сколько-то пакетов, и формально они потеряны — но записывать в «не
      // доехало» десятиминутную дыру бессмысленно: это счётчик качества
      // канала, а не журнал простоев.
      st.lastQ = null
    },

    stop () {
      stopLoop()
      clear()
    },

    stats () {
      return {
        lost: st.lost,
        dropped: st.dropped,
        buffered: st.buf.length,
        budgetMs: budget(),
        maxBuf: Math.ceil(budget() / STEP_MS),
        sessionId: st.sessionId,
        online: st.online,
      }
    },
  }
}
