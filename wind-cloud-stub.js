// Подставляется вместо wind-cloud.jsx в сборке WIND_SINGLE=1 (см. resolve.alias
// в wind-ui/vite.config.js).
//
// Причина — не экономия байтов, а канал распространения. WIND_SINGLE ставит
// inlineDynamicImports, который склеивает динамические чанки ОБРАТНО в entry:
// без подмены пароль зрителя оказался бы открытым текстом в
// dist-single/assets/index-*.js, а этот файл вставляется руками в артефакт
// claude.ai — другая аудитория, другой канал, и отозвать его нельзя.
//
// Лечится выбрасыванием, а не инлайном, и сразу двумя способами: этим алиасом
// и флагом __WIND_CLOUD__, который делает сам import() мёртвым кодом. Один
// способ — это точка отказа; два независимых — это запас.
//
// Форма экспортов обязана совпадать с wind-cloud.jsx до последнего имени:
// дашборд импортирует модуль динамически и вызывает то же самое, а падать
// вместо облака он не должен.

export const CLOUD_CONFIGURED = false

export function connect () {
  return {
    onState () {},
    onStatus () {},
    onLive () {},
    onPhase (fn) {
      // Одно сообщение всё-таки отдаём: молчащий канал неотличим от
      // зависшего, а здесь причина известна заранее и она окончательная.
      if (fn) fn('failed', 'в этой сборке облачного канала нет')
    },
    stats () {
      return { lost: 0, dropped: 0, buffered: 0 }
    },
    close () {},
  }
}

export function probeStatus () {
  return Promise.resolve({
    ok: false,
    online: null,
    error: 'в этой сборке облачного канала нет',
  })
}
